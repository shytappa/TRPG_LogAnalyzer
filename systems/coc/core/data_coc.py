# ==========================================
# 技能の一覧から、名前で引く表を作る（技能名 → 初期値 / 並び順）
# ==========================================
def _all_names(skill):
    return (skill.name, *skill.aliases)

def _initial_values(skills):
    return {n: s.initial for s in skills for n in _all_names(s)}

def _paren_initial_values(skills):
    """括弧書き（「芸術（歌）」など）の初期値を決める、括弧の外の名前 → 初期値"""
    return {n: s.initial for s in skills if s.paren_order is not None and s.paren_initial for n in _all_names(s)}

def _sort_orders(skills):
    orders = {n: s.order for s in skills for n in _all_names(s)}
    # 括弧書きは「運転（」のような頭の部分で前方一致させる（skills_coc.get_skill_sort_rank）
    orders.update({f"{n}（": s.paren_order for s in skills if s.paren_order is not None for n in _all_names(s)})
    return orders

def _non_growable(skills):
    return {n for s in skills if not s.grows for n in _all_names(s)}

